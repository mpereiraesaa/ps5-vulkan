EXT_RULE_RE = re.compile(r"^(?P<exts>.+?)\s*,?\s*if the (?P<feature>[A-Za-z0-9_]+) feature is supported\.?$")


def parse_extension_rule(text: str) -> dict:
    """Give the residual rules a taxonomy instead of leaving them as prose.

    Two shapes occur in the pinned section: "extension X (or core version), if
    feature Y is supported" (an extension requirement triggered by a feature),
    and the 1.4 queue-family / host-image-copy either-or rule.
    """
    match = EXT_RULE_RE.match(text.strip())
    if match:
        raw = match.group("exts").replace(" extension", "").replace("the ", "")
        extensions = [name.strip() for name in re.split(r",|\bor\b", raw) if name.strip()]
        return {
            "kind": "extension-required-by-feature",
            "extensions": extensions,
            "trigger": {"kind": "feature", "name": match.group("feature")},
            "requirement": {"kind": "any-of", "extensions": extensions},
            "text": text.strip(),
            "explanation": "One of these extensions (or the named core version) must be supported when %s is supported" % match.group("feature"),
        }
    if "hostImageCopy" in text:
        return {
            "kind": "either-or",
            "options": ["hostImageCopy feature supported", "an additional transfer-capable queue family reported"],
            "requirement": {"kind": "any-of", "features": ["hostImageCopy"]},
            "trigger": {"kind": "graphics-queue-without-extra-transfer-queue"},
            "text": text.strip(),
            "explanation": "A graphics-only queue configuration must provide either host image copy or an extra transfer-capable queue family",
        }
    return {"kind": "unclassified", "text": text.strip(), "explanation": ""}


def classify_commands(commands: list[str]) -> dict:
    """Group the resolved core command surface into differentiable contracts."""
    contracts: dict[str, list[str]] = {name: [] for name, _ in COMMAND_AREAS}
    contracts["command-recording"] = []
    contracts["other"] = []
    for command in commands:
        if command.startswith("vkCmd"):
            contracts["command-recording"].append(command)
            continue
        for name, prefixes in COMMAND_AREAS:
            if any(command.startswith(prefix) for prefix in prefixes):
                contracts[name].append(command)
                break
        else:
            contracts["other"].append(command)
    return {name: value for name, value in contracts.items() if value}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sources", default=DEFAULT_SOURCES)
    parser.add_argument("--out", default=DEFAULT_OUT)
    parser.add_argument("--spec-html", help="local copy of the pinned specification HTML")
    parser.add_argument("--vk-xml", help="local copy of the pinned registry vk.xml")
    parser.add_argument("--limits-adoc", help="local copy of the pinned chapters/limits.adoc")
    parser.add_argument("--formats-adoc", help="local copy of the pinned chapters/formats.adoc")
    args = parser.parse_args(argv)

    sources = load_sources(args.sources)
    spec = find_source(sources, SPEC_SOURCE_ID)
    registry = find_source(sources, REGISTRY_SOURCE_ID)
    alias = spec["document_alias"]
    vk_xml_artifact = next(a for a in registry["artifacts"] if a["path"] == "registry/vk.xml")
    limits_artifact = next(a for a in spec["artifacts"] if a["path"] == "chapters/limits.adoc")
    formats_artifact = next(a for a in spec["artifacts"] if a["path"] == "chapters/formats.adoc")

    html = read_input(args.spec_html, alias["url"], alias["sha256"], "specification").decode("utf-8", "replace")
    title = re.search(r"<title>([^<]*)</title>", html, re.IGNORECASE)
    if not title or spec["spec_version"] not in title.group(1):
        raise SystemExit("specification title does not report %s" % spec["spec_version"])
    xml_bytes = read_input(
        args.vk_xml,
        "https://raw.githubusercontent.com/KhronosGroup/Vulkan-Headers/%s/%s" % (registry["commit"], vk_xml_artifact["path"]),
        vk_xml_artifact["sha256"],
        "registry",
    )

    features = parse_feature_requirements(html)
    surface = parse_vk_xml(xml_bytes.decode("utf-8"))
    limits_bytes = read_input(
        args.limits_adoc,
        "https://raw.githubusercontent.com/KhronosGroup/Vulkan-Docs/%s/%s" % (spec["commit"], limits_artifact["path"]),
        limits_artifact["sha256"],
        "limits chapter",
    )
    formats_bytes = read_input(
        args.formats_adoc,
        "https://raw.githubusercontent.com/KhronosGroup/Vulkan-Docs/%s/%s" % (spec["commit"], formats_artifact["path"]),
        formats_artifact["sha256"],
        "formats chapter",
    )
    limits_table = parse_limits_table(limits_bytes.decode("utf-8"))
    formats_tables = parse_formats_tables(formats_bytes.decode("utf-8"))
    resolved_commands = surface["surface_by_profile"]["graphics_resolved"]["commands"]
    contracts = classify_commands(resolved_commands)

    spec_by_version = {}
    unconditional: list[dict] = []
    conditional: list[dict] = []
    at_least_one: list[dict] = list(features["at_least_one"])
    for version, entries in sorted(features["by_version"].items()):
        bits, conditional_bits = [], []
        for entry in entries:
            record = {
                "features": entry["features"],
                "condition": entry["condition"],
                "at_least_one": entry["at_least_one"],
                "text": entry["text"],
            }
            if entry["at_least_one"]:
                at_least_one.append(dict(record, version=version))
            elif entry["condition"] and "is not advertised" in entry["condition"]:
                # A negative condition ("unless this extension is advertised")
                # holds for any implementation that does not advertise the
                # named extension, so the obligation is treated as
                # unconditional and the condition is preserved as a note.
                record["note"] = "condition: " + entry["condition"]
                bits.append(record)
                unconditional.append(dict(record, version=version))
            elif entry["condition"]:
                conditional_bits.append(record)
                conditional.append(dict(record, version=version))
            else:
                bits.append(record)
                unconditional.append(dict(record, version=version))
        spec_by_version[version] = {"unconditional": bits, "conditional": conditional_bits}
    conditional_on_optional_extension = []
    any_of_groups = 0
    for entry in features["conditional_features"] + features.get("by_version", {}).get("__none__", []):
        if not isinstance(entry, dict) or "features" not in entry:
            continue
        trigger = entry.get("trigger") or parse_trigger(" or ".join(entry.get("extensions", [])) + " is supported")
        record = {
            "features": list(entry["features"]),
            "requirement": entry.get("requirement") or (
                {"kind": "any-of", "features": list(entry["features"])}
                if entry.get("at_least_one") and len(entry["features"]) > 1
                else {"kind": "feature", "features": list(entry["features"][:1])}
            ),
            "trigger": trigger,
            "condition": entry.get("condition") or condition_explanation(trigger),
            "at_least_one": bool(entry.get("at_least_one")),
            "text": entry["text"],
            "explanation": entry.get("explanation") or "",
            "version": None,
        }
        if record["at_least_one"]:
            any_of_groups += 1
        conditional_on_optional_extension.append(record)
    # Any-of alternatives must not be re-expanded into separate obligations.
    expanded = [entry for entry in conditional_on_optional_extension if len(entry["features"]) == 1 and entry["at_least_one"]]
    if expanded:
        raise SystemExit("any-of group was expanded into single-feature obligations: %r" % expanded[:2])

    # Cross-check the two primary sources: the specification's per-version
    # unconditional feature lists must agree with the registry's per-version
    # <feature> requirement lists.
    spec_bits_by_version = {
        version: sorted({bit for entry in payload["unconditional"] for bit in entry["features"]})
        for version, payload in spec_by_version.items()
    }
    xml_bits_by_version = surface["mandatory_feature_bits_by_version"]
    mismatches = []
    for version in sorted(set(spec_bits_by_version) | set(xml_bits_by_version)):
        spec_bits = set(spec_bits_by_version.get(version, []))
        xml_bits = set(xml_bits_by_version.get(version, []))
        if spec_bits != xml_bits:
            mismatches.append(
                {
                    "version": version,
                    "spec_only": sorted(spec_bits - xml_bits),
                    "registry_only": sorted(xml_bits - spec_bits),
                }
            )
    cumulative_bits = sorted({bit for value in xml_bits_by_version.values() for bit in value})

    output = {
        "schema_version": "1.0",
        "target": {
            "id": "ps5vk-vulkan14-graphics-core",
            "statement": "Declared project target: Vulkan 1.4 core for a graphics implementation. This is a target, not a claim of support.",
            "definition": "The cumulative core obligations of Vulkan 1.0 through 1.4; not a roadmap profile and not a consumer requirement set.",
            "basis": {
                "feature_requirements": {
                    "source_id": SPEC_SOURCE_ID,
                    "anchor": "features-requirements",
                    "spec_version": spec["spec_version"],
                    "document_sha256": alias["sha256"],
                    "note": "Section 'Feature Requirements': every Vulkan graphics implementation must support the listed features per core version, with the stated conditions.",
                },
                "api_surface": {
                    "source_id": REGISTRY_SOURCE_ID,
                    "path": vk_xml_artifact["path"],
                    "sha256": vk_xml_artifact["sha256"],
                    "note": "Per-version <feature> blocks list the commands, types and enums each core version requires.",
                },
                "enforcement_reference": {
                    "source_id": "khronos-vk-gl-cts",
                    "path": "external/vulkancts/modules/vulkan/api/vktApiFeatureInfo.cpp",
                    "note": "The CTS device_mandatory_features case is generated from vkMandatoryFeatures.inl and points at the specification anchor features-requirements.",
                },
            },
        },
        "mandatory_feature_bits": {
            "registry_by_version": xml_bits_by_version,
            "cumulative": cumulative_bits,
            "specification_by_version": spec_by_version,
            "specification_registry_mismatches": mismatches,
            "conditional_in_version_blocks": [
                dict(entry) for entry in conditional if entry["version"] is not None
            ],
            "conditional_on_optional_extension": conditional_on_optional_extension,
            "at_least_one_groups": at_least_one,
            "extension_rules": [parse_extension_rule(text) for text in features["unclassified"]],
        },
        "api_surface": surface,
        "limits": {
            "source_anchor": "limits-required",
            "resolution_rule": "values tagged {core} or {limit1_4} apply to the core target; {limit2022}/{limit2024}/{limit2026} values are roadmap-only and are recorded separately",
            "raised_in_1_4": sorted({row["limit"] for row in limits_table if any("1_4" in value["tags"] for value in row["values"])}),
            "rows": limits_table,
        },
        "formats": {
            "source_anchors": [table["anchor"] for table in formats_tables],
            "resolution_rule": "each row is a format plus the feature bits the specification requires for it; an empty marker means the feature is not mandatory for that format",
            "tables": formats_tables,
        },
        "command_contracts": {
            "resolution_rule": "the resolved core command surface grouped into differentiable contracts by API area; one requirement row per contract",
            "contracts": contracts,
        },
        "roadmap_comparison": {
            "file": "roadmap_comparison.json",
            "note": "Khronos roadmap profiles are recorded separately as a comparison. They are not the definition of core conformance and must not drive classification.",
        },
    }

    tmp = args.out + ".tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        json.dump(output, handle, indent=2, sort_keys=True)
        handle.write("\n")
    os.replace(tmp, args.out)
    log(
        "wrote %s: %d unconditional bits, %d conditional entries, %d at-least-one groups, %d cumulative commands"
        % (
            args.out,
            len(cumulative_bits),
            len(conditional),
            len(at_least_one),
            len(surface["surface_by_profile"]["graphics_including_base"]["commands"]),
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
