static inline unsigned ps5vk_bc_blit_block_bytes(enum ps5vk_bc_blit_format format)
{
    switch (format) {
    case PS5VK_BC_BLIT_BC1_RGB_UNORM:
    case PS5VK_BC_BLIT_BC1_RGB_SRGB:
    case PS5VK_BC_BLIT_BC1_RGBA_UNORM:
    case PS5VK_BC_BLIT_BC1_RGBA_SRGB:
    case PS5VK_BC_BLIT_BC4_UNORM:
    case PS5VK_BC_BLIT_BC4_SNORM:
        return 8;
    case PS5VK_BC_BLIT_BC2_UNORM:
    case PS5VK_BC_BLIT_BC2_SRGB:
    case PS5VK_BC_BLIT_BC3_UNORM:
    case PS5VK_BC_BLIT_BC3_SRGB:
    case PS5VK_BC_BLIT_BC5_UNORM:
    case PS5VK_BC_BLIT_BC5_SNORM:
    case PS5VK_BC_BLIT_BC6H_UFLOAT:
    case PS5VK_BC_BLIT_BC6H_SFLOAT:
    case PS5VK_BC_BLIT_BC7_UNORM:
    case PS5VK_BC_BLIT_BC7_SRGB:
        return 16;
    default:
        return 0;
    }
}

static inline int ps5vk_bc_blit_srgb(enum ps5vk_bc_blit_format format)
{
    return format == PS5VK_BC_BLIT_BC1_RGB_SRGB ||
        format == PS5VK_BC_BLIT_BC1_RGBA_SRGB ||
        format == PS5VK_BC_BLIT_BC2_SRGB || format == PS5VK_BC_BLIT_BC3_SRGB ||
        format == PS5VK_BC_BLIT_BC7_SRGB;
}

static inline uint8_t ps5vk_bc_blit_unorm8(float value)
{
    if (!(value > 0.0f)) return 0;
    if (value >= 1.0f) return 255;
    return (uint8_t)(value * 255.0f + 0.5f);
}

