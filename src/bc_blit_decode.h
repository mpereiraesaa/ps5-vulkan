/* Decode to Vulkan's numeric values before destination conversion. Keeping
 * float values matters for linear blits from SNORM/float BC formats: filtering
 * is performed before the UNORM destination clamps negative or >1 values. */
static inline int ps5vk_bc_blit_decode_float(enum ps5vk_bc_blit_format format,
                                             const uint8_t *block, float rgba[16][4])
{
    if (!block || !rgba || !ps5vk_bc_blit_block_bytes(format)) return 0;
    uint8_t decoded[16][4] = {{0}};
    uint8_t scalar_bytes[32] = {0};
    float scalar[16 * 3] = {0};
    int floating = 0;
    switch (format) {
    case PS5VK_BC_BLIT_BC1_RGB_UNORM:
    case PS5VK_BC_BLIT_BC1_RGB_SRGB:
    case PS5VK_BC_BLIT_BC1_RGBA_UNORM:
    case PS5VK_BC_BLIT_BC1_RGBA_SRGB:
        bcdec_bc1(block, decoded, 16);
        if (format == PS5VK_BC_BLIT_BC1_RGB_UNORM ||
            format == PS5VK_BC_BLIT_BC1_RGB_SRGB)
            for (unsigned i = 0; i < 16; ++i) decoded[i][3] = 255;
        break;
    case PS5VK_BC_BLIT_BC2_UNORM:
    case PS5VK_BC_BLIT_BC2_SRGB:
        bcdec_bc2(block, decoded, 16); break;
    case PS5VK_BC_BLIT_BC3_UNORM:
    case PS5VK_BC_BLIT_BC3_SRGB:
        bcdec_bc3(block, decoded, 16); break;
    case PS5VK_BC_BLIT_BC4_UNORM:
        bcdec_bc4(block, scalar_bytes, 4, 0); break;
    case PS5VK_BC_BLIT_BC4_SNORM:
        bcdec_bc4_float(block, scalar, 4, 1); floating = 1; break;
    case PS5VK_BC_BLIT_BC5_UNORM:
        bcdec_bc5(block, scalar_bytes, 8, 0); break;
    case PS5VK_BC_BLIT_BC5_SNORM:
        bcdec_bc5_float(block, scalar, 8, 1); floating = 1; break;
    case PS5VK_BC_BLIT_BC6H_UFLOAT:
        bcdec_bc6h_float(block, scalar, 12, 0); floating = 1; break;
    case PS5VK_BC_BLIT_BC6H_SFLOAT:
        bcdec_bc6h_float(block, scalar, 12, 1); floating = 1; break;
    case PS5VK_BC_BLIT_BC7_UNORM:
    case PS5VK_BC_BLIT_BC7_SRGB:
        bcdec_bc7(block, decoded, 16); break;
    default:
        return 0;
    }

    const int srgb = ps5vk_bc_blit_srgb(format);
    for (unsigned i = 0; i < 16; ++i) {
        if (format == PS5VK_BC_BLIT_BC4_UNORM || format == PS5VK_BC_BLIT_BC4_SNORM) {
            rgba[i][0] = floating ? scalar[i] : (float)scalar_bytes[i] / 255.0f;
            rgba[i][1] = rgba[i][2] = 0.0f; rgba[i][3] = 1.0f;
        } else if (format == PS5VK_BC_BLIT_BC5_UNORM || format == PS5VK_BC_BLIT_BC5_SNORM) {
            rgba[i][0] = floating ? scalar[i * 2] : (float)scalar_bytes[i * 2] / 255.0f;
            rgba[i][1] = floating ? scalar[i * 2 + 1] : (float)scalar_bytes[i * 2 + 1] / 255.0f;
            rgba[i][2] = 0.0f; rgba[i][3] = 1.0f;
        } else if (format == PS5VK_BC_BLIT_BC6H_UFLOAT || format == PS5VK_BC_BLIT_BC6H_SFLOAT) {
            for (unsigned c = 0; c < 3; ++c)
                rgba[i][c] = scalar[i * 3 + c];
            rgba[i][3] = 1.0f;
        } else {
            for (unsigned c = 0; c < 4; ++c)
                rgba[i][c] = srgb && c < 3 ?
                    ps5vk_bc_blit_srgb_to_linear(decoded[i][c]) : (float)decoded[i][c] / 255.0f;
        }
    }
    return 1;
}

/* Convert a nearest sample to the final RGBA8_UNORM destination values. */
static inline int ps5vk_bc_blit_decode(enum ps5vk_bc_blit_format format,
                                       const uint8_t *block, uint8_t rgba[16][4])
{
    float decoded[16][4];
    if (!rgba || !ps5vk_bc_blit_decode_float(format, block, decoded)) return 0;
    for (unsigned i = 0; i < 16; ++i)
        for (unsigned c = 0; c < 4; ++c)
            rgba[i][c] = ps5vk_bc_blit_unorm8(decoded[i][c]);
    return 1;
}

